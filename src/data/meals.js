export const meals = { breakfasts, lunches, dinners };

export function getDailyMeals(seed) {
  const s = seed ?? new Date().getDate();
  const pick = (arr, offset) => arr[(s + offset) % arr.length];
  return {
    breakfast: pick(breakfasts, 0),
    lunch: pick(lunches, 1),
    dinner: pick(dinners, 2),
  };
}

export function getTotalMacros(daily) {
  const { breakfast, lunch, dinner } = daily;
  return {
    kcal: breakfast.kcal + lunch.kcal + dinner.kcal,
    protein: breakfast.protein + lunch.protein + dinner.protein,
    carbs: breakfast.carbs + lunch.carbs + dinner.carbs,
    fat: breakfast.fat + lunch.fat + dinner.fat,
  };
}
